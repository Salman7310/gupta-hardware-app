/**
 * Turns the .sql files drizzle-kit generates into a TypeScript module.
 *
 * Drizzle's own drizzle/migrations.js imports each .sql file directly, which
 * needs a Metro resolver change plus a Babel plugin that is incompatible with
 * the Babel version Expo ships. Emitting a plain .ts module instead keeps the
 * bundler entirely ordinary: no plugins, no custom source extensions.
 *
 * Runs automatically as part of `npm run db:generate`.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const drizzleDir = join(root, 'drizzle');
const journalPath = join(drizzleDir, 'meta', '_journal.json');
const outPath = join(root, 'src', 'data', 'db', 'migrations.generated.ts');

if (!existsSync(journalPath)) {
  console.error('No journal at ' + journalPath + '. Run drizzle-kit generate first.');
  process.exit(1);
}

const journal = JSON.parse(readFileSync(journalPath, 'utf8'));

const entries = journal.entries.map((entry) => {
  const sqlPath = join(drizzleDir, entry.tag + '.sql');
  if (!existsSync(sqlPath)) {
    console.error('Journal references ' + entry.tag + '.sql but it is missing.');
    process.exit(1);
  }
  const key = 'm' + String(entry.idx).padStart(4, '0');
  return '  ' + key + ': ' + JSON.stringify(readFileSync(sqlPath, 'utf8')) + ',';
});

const lines = [
  '// AUTO-GENERATED by scripts/build-migrations.mjs. Do not edit.',
  '// Regenerate with `npm run db:generate`.',
  '',
  'interface JournalEntry {',
  '  idx: number;',
  '  when: number;',
  '  tag: string;',
  '  breakpoints: boolean;',
  '  [key: string]: unknown;',
  '}',
  '',
  'interface Journal {',
  '  entries: JournalEntry[];',
  '  [key: string]: unknown;',
  '}',
  '',
  'const journal: Journal = ' + JSON.stringify(journal, null, 2) + ';',
  '',
  'const migrations: Record<string, string> = {',
  ...entries,
  '};',
  '',
  'export default { journal, migrations };',
  '',
];

writeFileSync(outPath, lines.join('\n'));
console.log('Wrote ' + entries.length + ' migration(s) to src/data/db/migrations.generated.ts');
